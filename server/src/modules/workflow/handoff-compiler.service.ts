// ---------------------------------------------------------------
// SSE writer helper
// ---------------------------------------------------------------
export class SSEStreamWriter {
    constructor(private res: Response) {}

    write(event: string, data: object) {
        this.res.write(`event: ${event}\ndata: ${JSON.stringify(data)}\n\n`);
    }

    progress(step: string, percent: number) {
        this.write("progress", { step, percent });
    }

    log(message: string) {
        this.write("log", { message });
    }

    complete(packageId: string, version: number) {
        this.write("complete", { packageId, version });
    }

    error(message: string) {
        this.write("error", { message });
    }
}

// ---------------------------------------------------------------
// Build master prompt (AI_IDE_START_HERE.md)
// ---------------------------------------------------------------
function buildMasterPrompt(vars: IHandoffCompilerVariables): string {
    return `# AI IDE Implementation Instructions — Start Here

You are an expert AI software engineer. You are tasked with implementing the software system defined in this handoff package.

## 1. Project Context
- **Project Name**: ${vars.ideaName}
- **Idea Description**: ${vars.ideaText}

## 2. Directory Map & Reading Order
Please read files in this sequence before writing any code:
1. \`AI_IDE_START_HERE.md\` (This file) — understand goal and rules
2. \`specifications/technical-specification.md\` — stack and environment
3. \`specifications/coding-standards.md\` — style and patterns
4. \`specifications/database-specification.md\` — schema and entities
5. \`specifications/api-specification.md\` — route contracts
6. \`implementation/implementation-roadmap.md\` — ordered task phases

## 3. Research Context
- \`research/research-summary.md\` — market research and competitor analysis
- \`documents/\` — PRD and BRD for product requirements

## 4. Diagrams
All diagrams in \`diagrams/\` are Mermaid format (.mmd). Read them to understand the system architecture, entity relationships, and user flows.

## 5. Strict Execution Rules
1. **Zero-Guessing Contracts**: Implement APIs and schemas EXACTLY as defined in \`specifications/\`.
2. **Compile-Check Cycle**: Compile and run tests at the end of each phase before moving to the next.
3. **No Orphan Code**: Do not create placeholder files or comment out existing code.
4. **Dependency Enforcement**: Do not start a task unless its dependencies (declared in \`implementation-roadmap.md\`) are complete.

## 6. Status Tracking
Create an \`IMPLEMENTATION_STATUS.md\` file at the project root. Update it after completing each phase with: phase name, tasks done, test results, and next steps.
`;
}

